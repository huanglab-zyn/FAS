#Fig7
library(Seurat)
library(ggplot2)
#Fig7A
SLE.data<- Read10X(data.dir = "/home/user1/file_10x_SLE/")
SLE <- CreateSeuratObject(counts = SLE.data, project = "SLE")
SLE <- NormalizeData(SLE, normalization.method = "LogNormalize", scale.factor = 10000)
SLE<- FindVariableFeatures(SLE, selection.method = "vst", nfeatures = 2000)
top100 <- head(VariableFeatures(SLE), 100)
all.genes <- rownames(SLE)
SLE <- ScaleData(SLE, features = all.genes)
SLE <- RunPCA(SLE, features = VariableFeatures(object = SLE))
DimPlot(SLE, reduction = "pca") + NoLegend()
print(SLE[["pca"]], dims = 1:10, nfeatures = 5)
DimHeatmap(SLE, dims = 1:20, cells = 500, balanced = TRUE)
ElbowPlot(SLE,ndims = 100)
SLE<- FindNeighbors(SLE, dims = 1:30)
SLE<- FindClusters(SLE, resolution = 0.5)
SLE<- RunUMAP(SLE, dims = 1:30)
DimPlot(SLE, reduction = "umap")
